// A deliberate, small type scale for the Kid Hub — bigger and bolder than the
// shared TYPO tokens (which top out around 13-15 for body text), because this
// is the "how am I doing" screen a kid checks first: it should read like a
// game HUD, not a dense adult dashboard. Six sizes, nothing improvised.
