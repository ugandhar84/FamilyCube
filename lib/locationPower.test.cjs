// Run: node lib/locationPower.test.cjs
const { transform } = require('../node_modules/sucrase');
const fs = require('fs'); const Module = require('module');
const m = new Module('p'); m._compile(transform(fs.readFileSync(__dirname + '/locationPower.ts', 'utf8'), { transforms: ['typescript', 'imports'] }).code, __dirname + '/lp.compiled.js');
const P = m.exports; let fail = 0;
const eq = (n, a, b) => { const ok = JSON.stringify(a) === JSON.stringify(b); if (!ok) { fail++; console.log('FAIL', n, a, '!=', b); } else console.log('ok  ', n); };
const T = 1_000_000;
const step = (st, o) => P.nextPowerState(st, { now: T, speedMph: 0, batteryLevel: 80, isCharging: false, ...o });
let s = P.initialPowerState();
eq('idle is stationary', step(s, {}).mode, 'stationary');
eq('walking speed -> walking', step(s, { speedMph: 3 }).mode, 'walking');
eq('car speed -> driving', step(s, { speedMph: 30 }).mode, 'driving');
eq('motion sensor says automotive at 0 mph -> driving', step(s, { automotive: true }).mode, 'driving');
let d = step(s, { speedMph: 30 });
eq('stopped at a light 60s later still driving', P.nextPowerState(d, { now: T + 60_000, speedMph: 0, batteryLevel: 80, isCharging: false }).mode, 'driving');
eq('stopped 3 min later back to stationary', P.nextPowerState(d, { now: T + 200_000, speedMph: 0, batteryLevel: 80, isCharging: false }).mode, 'stationary');
let w = step(s, { speedMph: 3 });
eq('walk paused 30s still walking', P.nextPowerState(w, { now: T + 30_000, speedMph: 0, batteryLevel: 80, isCharging: false }).mode, 'walking');
eq('walk stopped 2 min -> stationary', P.nextPowerState(w, { now: T + 120_000, speedMph: 0, batteryLevel: 80, isCharging: false }).mode, 'stationary');
let l = P.enterLive(s, T);
eq('live request -> live', step(l, {}).mode, 'live');
eq('live expires', P.nextPowerState(l, { now: T + 130_000, speedMph: 0, batteryLevel: 80, isCharging: false }).mode, 'stationary');
eq('live but critical battery -> not live', step(l, { batteryLevel: 5 }).mode, 'saver');
eq('low battery idle -> saver', step(s, { batteryLevel: 10 }).mode, 'saver');
eq('low battery but charging -> normal', step(s, { batteryLevel: 10, isCharging: true }).mode, 'stationary');
eq('low battery walking relaxes to saver', step(s, { batteryLevel: 10, speedMph: 3 }).mode, 'saver');
eq('low battery driving stays driving', step(s, { batteryLevel: 10, speedMph: 30 }).mode, 'driving');
eq('low power mode -> saver', step(s, { lowPowerMode: true }).mode, 'saver');
eq('driving beats live', step(l, { speedMph: 30 }).mode, 'driving');
eq('stationary pauses updates', P.POWER_CONFIG.stationary.pauses, true);
eq('driving is tighter than stationary', P.POWER_CONFIG.driving.distanceInterval < P.POWER_CONFIG.stationary.distanceInterval, true);
console.log(fail ? fail + ' FAILED' : 'all passed'); process.exit(fail ? 1 : 0);
